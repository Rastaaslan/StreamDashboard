const assert = require('node:assert/strict');
const {readFileSync} = require('node:fs');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require('@playwright/test');
const file = path.resolve('docs/streamcockpit-3/G3_INTERACTIVE_RECEPTION_20261105.html');
const testUrl = pathToFileURL(file).href;
let passed=0;
function pass(title){passed++;console.log('PASS '+passed+' '+title);}
(async()=>{
  const source=readFileSync(file,'utf8');
  assert.match(source, /Content-Security-Policy/);
  assert.match(source, /connect-src 'none'/);
  assert.doesNotMatch(source,/<script\s+src=/);
  assert.doesNotMatch(source,/fetch\(/);
  pass('offline source, no imported JS or fetch');
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:320,height:750},acceptDownloads:true});
    const external=[];const errs=[];
    page.on('request',req=>{if(!req.url().startsWith('file:')&&!req.url().startsWith('data:')&&!req.url().startsWith('blob:'))external.push(req.url());});
    page.on('pageerror',err=>errs.push(err.message));
    await page.goto(testUrl,{waitUntil:'load'});
    assert.equal(await page.locator('.item').count(),162);
    assert.equal(await page.locator('section.section').count(),14);
    assert.equal(await page.locator('.item select').count(),162);
    pass('14 sections, 162 scenarios, default controls');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= 320),true);
    assert.match(await page.locator('#critical').textContent(),/P0/);
    pass('Edge at 320px touch-width no viewport overflow');
    await page.locator('#fixe').fill('73a6aae QA');
    await page.locator('.item').first().locator('select').selectOption('pass');
    await page.locator('.item').first().locator('textarea').fill('Test manuel qualitatif');
    await page.reload({waitUntil:'load'});
    assert.equal(await page.locator('.item').first().locator('select').inputValue(),'pass');
    assert.equal(await page.locator('#fixe').inputValue(),'73a6aae QA');
    assert.equal(await page.locator('.item').first().locator('textarea').inputValue(),'Test manuel qualitatif');
    pass('local persistence survives reload');
    await page.locator('#filterText').fill('Wi-Fi');
    assert.ok(await page.locator('.item:visible').count()>0);
    assert.ok(await page.locator('.item:visible').count()<162);
    await page.locator('#filterText').fill('');
    await page.locator('#filterStatus').selectOption('pass');
    assert.equal(await page.locator('.item:visible').count(),1);
    await page.locator('#filterStatus').selectOption('all');
    pass('search and outcome filters');
    const waitDownload=page.waitForEvent('download');
    await page.locator('#exportJson').click();
    const download=await waitDownload;
    assert.ok(download.suggestedFilename().endsWith('.json'));
    const payload=JSON.parse(readFileSync(await download.path(),'utf8'));
    assert.equal(payload.qaSourceCommit,'73a6aae2a8e59c1c22c1f0d304cccb08c1586718');
    assert.equal(Object.keys(payload.results).length,162);
    assert.equal(payload.results['S00-01'].status,'pass');
    assert.equal(payload.kind,'manual-reception-only');
    pass('export JSON with source proof and 162 answers');
    const danger='<img src=x onerror=alert(1)> https://example.invalid/secret';
    const corrupted={...payload,results:{...payload.results,'S99-99':{status:'pass',note:'fake'}}};
    await page.locator('#importFile').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(corrupted))});
    assert.match(await page.locator('#notice').textContent(),/rejeté/i);
    assert.equal(await page.locator('.item').first().locator('select').inputValue(),'pass');
    pass('rejects injected non-existent scenario');
    const safe={...payload,results:{...payload.results,'S00-01':{status:'fail',note:danger}}};
    page.once('dialog',dlg=>dlg.accept());
    await page.locator('#importFile').setInputFiles({name:'valid.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(safe))});
    assert.equal(await page.locator('.item').first().locator('select').inputValue(),'fail');
    assert.equal(await page.locator('.item').first().locator('textarea').inputValue(),danger);
    assert.equal(await page.locator('img').count(),0);
    assert.equal(external.length,0);
    assert.equal(errs.length,0,errs.join('; '));
    pass('valid import uses text nodes, no HTML injection, no external requests');
    await page.locator('.item').first().locator('textarea').fill('=HYPERLINK("https://example.invalid/evil")');
    const csvTask=page.waitForEvent('download');
    await page.locator('#exportCsv').click();
    const csv=readFileSync(await (await csvTask).path(),'utf8');
    assert.match(csv, /"'=HYPERLINK\(""https:\/\/example.invalid\/evil""\)"/);
    pass('CSV formula injection neutralized before Excel import');
    page.once('dialog',dlg=>dlg.accept());
    await page.locator('#clearBtn').click();
    assert.equal(await page.locator('.item').first().locator('select').inputValue(),'todo');
    assert.equal(await page.locator('#fixe').inputValue(),'');
    pass('explicit-confirm reset without hidden defaults');
    console.log('RESULT '+passed+' PASS / 0 FAIL / 0 skipped; browser=Microsoft Edge (file://) at 320px; zero OBS/Twitch/network actions');
  }finally{await browser.close();}
})().catch(e=>{console.error('FAIL',e?.stack||e);process.exitCode=1;});